alter table public.apply_leave
  add column if not exists leave_request_id bigint generated by default as identity,
  add column if not exists user_id uuid references auth.users (id) on delete cascade,
  add column if not exists status text not null default 'Pending',
  add column if not exists applied_at timestamptz not null default now();

alter table public.apply_leave
  alter column emp_id type text using emp_id::text,
  alter column emp_id drop not null;

update public.admin as a
set user_id = u.id
from auth.users as u
where a.user_id is null
  and lower(a.email) = lower(u.email);

update public.employee as e
set user_id = u.id
from auth.users as u
where e.user_id is null
  and lower(e.email) = lower(u.email);

update public.apply_leave as l
set user_id = e.user_id
from public.employee as e
where l.user_id is null
  and l.emp_id = e.emp_id
  and e.user_id is not null;

create unique index if not exists employee_emp_id_unique
  on public.employee (emp_id)
  where emp_id is not null;

create unique index if not exists apply_leave_request_id_unique
  on public.apply_leave (leave_request_id);

create or replace function public.set_employee_auth_user_id()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  select u.id
  into new.user_id
  from auth.users as u
  where lower(u.email) = lower(new.email)
  limit 1;

  return new;
end;
$$;

drop trigger if exists set_employee_auth_user_id on public.employee;
create trigger set_employee_auth_user_id
before insert or update of email on public.employee
for each row execute function public.set_employee_auth_user_id();

