drop policy if exists "Admins can read their own profile" on public.admin;
create policy "Admins can read their own profile"
on public.admin
for select
to authenticated
using (lower(email) = lower((select auth.jwt() ->> 'email')));

drop policy if exists "Employees can read their own profile" on public.employee;
create policy "Employees can read their own profile"
on public.employee
for select
to authenticated
using (
  lower(email) = lower((select auth.jwt() ->> 'email'))
  or exists (
    select 1
    from public.admin as a
    where lower(a.email) = lower((select auth.jwt() ->> 'email'))
  )
);

